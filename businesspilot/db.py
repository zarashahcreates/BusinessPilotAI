"""SQLite persistence for saved analyses and generated reports.

Data persists on the machine running the app (``data/`` folder), across restarts. It is NOT shared
between devices and there are no user accounts, so do not host this publicly with sensitive data.
All SQL is parameterised and file names are generated by the app, never taken from users.
"""
from __future__ import annotations

import json
import sqlite3
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path
from typing import Optional

import pandas as pd

from . import config


class StorageError(RuntimeError):
    pass


def _paths():
    base = Path(config.DATA_DIR)
    return base, base / "datasets", base / "reports"


@contextmanager
def _conn():
    try:
        con = sqlite3.connect(str(config.DB_PATH), timeout=10)
        con.row_factory = sqlite3.Row
        con.execute("PRAGMA foreign_keys = ON")
    except sqlite3.Error as exc:
        raise StorageError(f"Could not open the database: {exc}") from exc
    try:
        yield con
        con.commit()
    except sqlite3.Error as exc:
        con.rollback()
        raise StorageError(f"Database error: {exc}") from exc
    finally:
        con.close()


def init_db() -> None:
    base, ds, rp = _paths()
    for d in (base, ds, rp):
        d.mkdir(parents=True, exist_ok=True)
    with _conn() as con:
        con.executescript("""
        CREATE TABLE IF NOT EXISTS analyses (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            business_name TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            row_count INTEGER,
            settings_json TEXT,
            summary_md TEXT,
            dataset_file TEXT
        );
        CREATE TABLE IF NOT EXISTS reports (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            analysis_id INTEGER NOT NULL REFERENCES analyses(id) ON DELETE CASCADE,
            report_type TEXT, fmt TEXT NOT NULL, filename TEXT NOT NULL,
            created_at TEXT NOT NULL, path TEXT NOT NULL
        );
        """)


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def save_analysis(name: str, business_name: str, df: pd.DataFrame, settings: dict, summary_md: str = "",
                  analysis_id: Optional[int] = None) -> int:
    """Create or update a saved analysis. ``df`` is the raw merged table (before mapping)."""
    init_db()
    name = (name or "Untitled analysis").strip()[:120]
    _, ds, _ = _paths()
    with _conn() as con:
        if analysis_id is None:
            cur = con.execute("INSERT INTO analyses(name,business_name,created_at,updated_at,row_count,settings_json,summary_md) VALUES (?,?,?,?,?,?,?)",
                              (name, business_name, _now(), _now(), len(df), json.dumps(settings, default=str), summary_md))
            analysis_id = int(cur.lastrowid)
        else:
            con.execute("UPDATE analyses SET name=?,business_name=?,updated_at=?,row_count=?,settings_json=?,summary_md=? WHERE id=?",
                        (name, business_name, _now(), len(df), json.dumps(settings, default=str), summary_md, analysis_id))
        fname = f"analysis_{int(analysis_id)}.csv.gz"
        try:
            df.to_csv(ds / fname, index=False, compression="gzip")
        except OSError as exc:
            raise StorageError(f"Could not write the dataset file: {exc}") from exc
        con.execute("UPDATE analyses SET dataset_file=? WHERE id=?", (fname, analysis_id))
    return int(analysis_id)


def list_analyses() -> list[dict]:
    init_db()
    with _conn() as con:
        rows = con.execute("""SELECT a.id,a.name,a.business_name,a.created_at,a.updated_at,a.row_count,
                              (SELECT COUNT(*) FROM reports r WHERE r.analysis_id=a.id) AS n_reports
                              FROM analyses a ORDER BY a.updated_at DESC""").fetchall()
    return [dict(r) for r in rows]


def load_analysis(analysis_id: int) -> tuple[dict, pd.DataFrame, str]:
    init_db()
    with _conn() as con:
        row = con.execute("SELECT * FROM analyses WHERE id=?", (int(analysis_id),)).fetchone()
    if row is None:
        raise StorageError("That analysis no longer exists.")
    path = _paths()[1] / (row["dataset_file"] or "")
    if not row["dataset_file"] or not path.exists():
        raise StorageError("The saved data file for this analysis is missing, so it cannot be reopened.")
    try:
        df = pd.read_csv(path, compression="gzip")
    except Exception as exc:  # noqa: BLE001
        raise StorageError(f"The saved data file could not be read: {exc}") from exc
    return json.loads(row["settings_json"] or "{}"), df, row["summary_md"] or ""


def rename_analysis(analysis_id: int, new_name: str) -> None:
    new_name = (new_name or "").strip()[:120]
    if not new_name:
        raise StorageError("The name cannot be empty.")
    with _conn() as con:
        con.execute("UPDATE analyses SET name=?, updated_at=? WHERE id=?", (new_name, _now(), int(analysis_id)))


def delete_analysis(analysis_id: int) -> None:
    init_db()
    _, ds, rp = _paths()
    with _conn() as con:
        files = [r["path"] for r in con.execute("SELECT path FROM reports WHERE analysis_id=?", (int(analysis_id),))]
        row = con.execute("SELECT dataset_file FROM analyses WHERE id=?", (int(analysis_id),)).fetchone()
        con.execute("DELETE FROM analyses WHERE id=?", (int(analysis_id),))
    for f in files + ([str(ds / row["dataset_file"])] if row and row["dataset_file"] else []):
        try:
            Path(f).unlink(missing_ok=True)
        except OSError:
            pass


def save_report_file(analysis_id: int, report_type: str, fmt: str, filename: str, content: bytes) -> int:
    if not content:
        raise StorageError("Refusing to save an empty report.")
    init_db()
    _, _, rp = _paths()
    with _conn() as con:
        cur = con.execute("INSERT INTO reports(analysis_id,report_type,fmt,filename,created_at,path) VALUES (?,?,?,?,?,'')",
                          (int(analysis_id), report_type, fmt, filename, _now()))
        rid = int(cur.lastrowid)
        path = rp / f"report_{rid}.{fmt}"
        try:
            path.write_bytes(content)
        except OSError as exc:
            raise StorageError(f"Could not write the report file: {exc}") from exc
        con.execute("UPDATE reports SET path=? WHERE id=?", (str(path), rid))
    return rid


def list_reports(analysis_id: int) -> list[dict]:
    init_db()
    with _conn() as con:
        rows = con.execute("SELECT id,report_type,fmt,filename,created_at,path FROM reports WHERE analysis_id=? ORDER BY id DESC", (int(analysis_id),)).fetchall()
    return [dict(r) for r in rows]


def read_report_file(report_id: int) -> tuple[str, bytes]:
    with _conn() as con:
        row = con.execute("SELECT filename,path FROM reports WHERE id=?", (int(report_id),)).fetchone()
    if row is None or not Path(row["path"]).exists():
        raise StorageError("This report file is no longer available on disk.")
    return row["filename"], Path(row["path"]).read_bytes()
